"""Writes the Yggdrasil launcher icon (Rings + Flip) from geom.py:
adaptive foreground + monochrome vectors, and SVG sources for the legacy PNGs."""
import sys, os
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from geom import *

res, out = sys.argv[1], sys.argv[2]
BANDS = ring_bands()


def stroke(d, w, color, alpha=None):
    a = f'\n        android:strokeAlpha="{alpha}"' if alpha else ""
    return f'''    <path
        android:pathData="{d}"
        android:strokeWidth="{f(w)}"
        android:strokeColor="{color}"{a}
        android:strokeLineCap="round" />'''


def layer(mono):
    o = []
    for d in roots_paths():
        o.append(stroke(d, TRUNK_W, "#FFFFFFFF" if mono else ROOT, "0.5" if mono else None))
    for i in ORDER:
        d, _ = page_shape(i)
        if not mono:   # paper-coloured edge between overlapping pages
            o.append(f'''    <path
        android:pathData="{d}"
        android:fillColor="#FFFFFF"
        android:strokeColor="#FFFFFF"
        android:strokeWidth="1.2"
        android:strokeLineJoin="round" />''')
        col = "#FFFFFFFF" if mono else page_color(i)
        o.append(f'''    <group android:name="page{i + 1}">
        <clip-path android:pathData="{d}" />
        <path
            android:pathData="{BANDS}"
            android:fillColor="{col}"
            android:fillType="evenOdd" />
    </group>''')
    ink = "#FFFFFFFF" if mono else GREEN
    o.append(stroke(trunk_path(), TRUNK_W, ink))
    for d, w in book_paths():
        o.append(stroke(d, w, ink))
    return "\n".join(o)


HEAD = '''<?xml version="1.0" encoding="utf-8"?>
<!-- {what}
     Generated by branding/android.py from branding/geom.py: nine pages fan up from the book's
     spine to one hidden circle, cut by nine evenly spaced growth rings. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
'''
open(f"{res}/drawable/ic_yggdrasil_fg.xml", "w").write(
    HEAD.format(what="Yggdrasil launcher icon, foreground: an open book whose pages fan into the world tree.")
    + layer(False) + "\n</vector>\n")
open(f"{res}/drawable/ic_yggdrasil_mono.xml", "w").write(
    HEAD.format(what="Yggdrasil themed (monochrome) icon: the same mark in one colour; Android tints it.")
    + layer(True) + "\n</vector>\n")

m = mark2_svg(uid="L")
for name, bg in (("ic_yggdrasil", '<rect x="19" y="19" width="70" height="70" rx="16" fill="#fff"/>'),
                 ("ic_yggdrasil_round", '<circle cx="54" cy="54" r="35" fill="#fff"/>')):
    open(f"{out}/{name}.svg", "w").write(
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="17 17 74 74">{bg}{m}</svg>')
